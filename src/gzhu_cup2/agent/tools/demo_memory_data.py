def _ts(days_ago: int, hour: int = 21) -> float:
    """把"距今第几天"换算成时间戳(当天 hour 点)。"""
    day = datetime.now().replace(hour=0, minute=0, second=0, microsecond=0)
    return (day - timedelta(days=int(days_ago)) + timedelta(hours=hour)).timestamp()
